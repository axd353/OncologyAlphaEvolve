from __future__ import annotations

from collections import OrderedDict
from dataclasses import dataclass
from dataclasses import field
from pathlib import Path
from typing import TYPE_CHECKING, Any, Mapping, Protocol

if TYPE_CHECKING:
    from funsearch_pipeline.program_database.database import CandidateProgram


@dataclass(frozen=True)
class PairScore:
    """Score for one training/testing data pair.

    Input fields:
        name: Pair name from the config.
        score: Scalar score for that pair, where higher is better.

    Output use:
        Stored in the program database signature before the final mean score.
    """

    name: str
    score: float


@dataclass(frozen=True)
class EvaluatedCandidate:
    """Evaluation result for one candidate priority function.

    Input fields:
        candidate: Candidate program that was evaluated.
        pair_scores: Per-pair scores from configured data pairs.
        reduced_score: Final scalar score used for improvement checks.
        auxiliary_scores: Extra diagnostics stored in the program database
            signature before `mean`, so they do not control island ranking.
        metadata: Optional evaluator-specific diagnostics.

    Output use:
        Converted to upstream FunSearch `scores_per_test` for database
        registration.
    """

    candidate: CandidateProgram
    pair_scores: tuple[PairScore, ...]
    reduced_score: float
    auxiliary_scores: Mapping[str, float] = field(default_factory=dict)
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def scores_per_test(self) -> OrderedDict[str, float]:
        """Return scores in the shape expected by upstream FunSearch.

        Input:
            No arguments; reads pair scores and reduced score from this result.

        Output:
            Ordered mapping where each pair has a score and the final `mean`
            entry is last, so upstream `_reduce_score` ranks by the mean.
        """

        ordered_scores: OrderedDict[str, float] = OrderedDict()
        for pair_score in self.pair_scores:
            ordered_scores[pair_score.name] = pair_score.score
        for score_name, score_value in self.auxiliary_scores.items():
            ordered_scores[score_name] = score_value
        ordered_scores["mean"] = self.reduced_score
        return ordered_scores


